def parse_k(t):
    """Як A.parse, але без редакторської примітки джерела сучасною російською (канон за болящего, 6-та пісня)
    і з перекладом абзаців із RU_PARAS."""
    items, inl = _parse(t)
    out = []
    for kind, x in items:
        if kind == 'p':
            if x.startswith('В молитвословах, очень часто'): continue
            plain = x.replace('\u0301', '')
            tr = next((v for k, v in RU_PARAS.items() if plain.startswith(k)), None)
            if tr:
                out.append((kind, '{%d}' % len(inl))); inl.append(tr); continue
        out.append((kind, x))
    return out, inl


A.parse = parse_k


def main():
    db = sqlite3.connect(A.DB)
    os.makedirs(A.OUT, exist_ok=True)
    books, meta, rep = [], [], {}
    for aid, u, e in TITLES:
        g = db.execute('select id_group from prayers_ru_ak where _id=?', (aid,)).fetchone()[0]
        b, amb, unk = A.build(aid, u, e, db)
        books.append((aid, GROUP[g], b))
        rep[aid] = {'ambig': amb, 'unknown': unk}
    shards, cur, size, last = [], [], 0, None
    for aid, g, b in books:
        n = len(json.dumps(b, ensure_ascii=False, separators=(',', ':')).encode())
        if cur and (g != last or size + n > 450_000):
            shards.append(cur); cur, size = [], 0
        cur.append((aid, g, b)); size += n; last = g
    shards.append(cur)
    for si, sh in enumerate(shards):
        js = json.dumps([b for _, _, b in sh], ensure_ascii=False, separators=(',', ':'))
        with open(os.path.join(A.OUT, f'kn{si}.ts'), 'w', encoding='utf8') as f:
            f.write("// Канони з AlexandrKozlovskiy/OrthodoxCalendar (Apache-2.0), Київський ізвод: транслітерація правилами віра.укр.\n"
                    "// Файл згенеровано scripts/build_kz_kanony.py. Абзац з префіксом § — рубрика, з префіксом # — підзаголовок.\n"
                    "import type { MvBook } from '../molytvoslov';\n"
                    f"const D: MvBook[] = {js};\nexport default D;\n")
        for ix, (aid, g, b) in enumerate(sh):
            meta.append((aid, si, ix, g, b['u'], b['e']))
    with open(os.path.join(A.OUT, 'knMeta.ts'), 'w', encoding='utf8') as f:
        f.write("// Перелік канонів з ./kn<N>.ts (генерує scripts/build_kz_kanony.py): [id у джерелі, шард, номер у шарді, група, назва, назва англ.].\n"
                "// Тексти шардів завантажуються за потреби — див. KN_LOAD.\n"
                f"export const KZ_KN: [number, number, number, number, string, string][] = {json.dumps(meta, ensure_ascii=False, separators=(',', ':'))};\n"
                "import type { MvBook } from '../molytvoslov';\n"
                "/** Ліниве завантаження шарда з текстами канонів. */\n"
                "export const KN_LOAD: (() => Promise<MvBook[]>)[] = [\n"
                + ''.join(f"  () => import('./kn{i}').then((m) => m.default),\n" for i in range(len(shards))) + "];\n")
    print(len(books), 'книг,', len(shards), 'шардів')
    if A.MISS:
        print('НЕ ПЕРЕКЛАДЕНО:'); [print(' ', k, v[:3]) for k, v in sorted(A.MISS.items())]
    if A.REPORT: json.dump(rep, open(A.REPORT, 'w', encoding='utf8'), ensure_ascii=False)


main()
