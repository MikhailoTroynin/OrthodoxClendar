def inline(key):
    if key in WORDS: return WORDS[key]
    if key in LABEL: return LABEL[key]
    m = re.fullmatch(r'\((\d+)\)', key)
    if m: return key
    m = re.fullmatch(r'\(?(\d+) раз\)?\.?', key)
    if m: return f'({m[1]} разів)'
    return None


