import re
WORD=re.compile(r"[А-Яа-яЁё]+")
DEF=set('меня тебя чтобы чтоб который которая которые которого которой которых которому которую которым этот эта это эти этой этого этих этим этом эту хочу могу пожалуйста нужно надо нельзя только потому никогда очень нет если сколько ведь я мной тобой дай дайте помоги позволь пошли будь будьте всем всех вся все весь что как так уже тоже вот тут здесь сейчас теперь они она оно его ее её им их него неё ему ею была были было быть будет будут можно мы нас нам нами вы вас вам вами'.split())
# слабкі (спільні з ЦС) — не враховуються як ознака
WEAK=set('все всех всем весь вся что как так уже тоже вот они она оно его ее её им их него неё ему ею была были было быть будет будут можно мы нас нам нами вы вас вам вами тут здесь сейчас теперь будь будьте'.split())
STRONG=DEF-WEAK
MOD=re.compile(r'\b\w{3,}(ого|его|ому|ему|ую|юю|ой)\b',re.I)
CSM=re.compile(r'\b(яко|аще|еси|мя|Тя|тя|ми|ти|ны|вся|сия|сей|сего|иже|ихже|паки|убо|идеже|яже|еже|ея|аз|несть|ныне|присно|веки|рабы|Тебе|тебе)\b|\w{3,}(аго|яго|ыя|ия|еши|ети|ете)\b',re.I)


def feats(p):
    ws=[w.lower() for w in WORD.findall(p.replace('́',''))]
    return sum(1 for w in ws if w in STRONG),len(ws)
def is_ru(p):
    """Абзац схожий на сучасну російську: є хоча б одне суто російське слово, а наголосів (U+0301) мало —
    церковнослов'янські тексти джерела ідуть із наголосами."""
    s,n=feats(p)
    ac=p.count('\u0301')
    if ac>0.08*max(1,n): return False
    cs=len(CSM.findall(p))
    if s>=1: return not (cs>=3 and cs>=2*s)
    # сучасні закінчення (-ого, -ому, -ую, -ой) при майже відсутніх церковнослов'янських ознаках
    return len(MOD.findall(p))>=2 and len(CSM.findall(p))<=1
